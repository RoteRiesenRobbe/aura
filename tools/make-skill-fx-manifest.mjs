/**
 * Writes `api/skill-fx/bodies.json`, Go's copy of the skill-VFX body folder
 * (plan-skill-vfx.md §12f.4 C, C3a).
 *
 *     node tools/make-skill-fx-manifest.mjs
 *
 * ⭐ THE FOLDER IS THE SOURCE, this list is only Go's copy of it. The art
 * lives in the frontend and is bundled by webpack like every other texture
 * (`require.context` over the folder, the `RegionPaint.ts` precedent), so the
 * CLIENT never reads this file. Go does: it is the only way the content
 * validator can tell an authored `"body": "sword"` from a typo, and aurad
 * serves no binary art and gains no endpoint for it.
 *
 * ⚑ RUN IT AFTER ADDING OR REMOVING A PNG. A Go test (cmd/aurad,
 * TestSkillFxBodies_MatchTheArtFolder) fails when the folder and this list
 * differ in either direction, so a forgotten run is loud rather than a body
 * that validates and does not draw.
 *
 * ⚑ A NAME IS THE FILE STEM, VERBATIM. `arrow.png` is `arrow`; the reserved
 * frame naming (`foo_0.png`, `foo_1.png`, ...) simply lists as `foo_0` and
 * `foo_1` - frame playback is not built, and when it is, it is the ENGINE that
 * learns to group them, not this script (§12f.2).
 */
import {readdirSync, writeFileSync, mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname, join} from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BODIES = join(ROOT, 'frontend/src/features/skill-fx/assets/bodies');
const OUT_DIR = join(ROOT, 'api/skill-fx');
const OUT = join(OUT_DIR, 'bodies.json');

const names = readdirSync(BODIES)
    .filter((f) => f.endsWith('.png'))
    .map((f) => f.slice(0, -'.png'.length))
    .sort();

// Sorted, two-space indented, one trailing newline: the file is regenerated
// often and a diff should only ever show the names that changed.
const manifest = {
    _comment: 'GENERATED by tools/make-skill-fx-manifest.mjs, its single writer - '
        + 'do not hand-edit. The names are the PNG file stems in '
        + 'frontend/src/features/skill-fx/assets/bodies/, which is the source of '
        + 'truth; this is Go\'s copy of it, read only by the content validator '
        + '(a skill\'s visual layer may name one of these as its "body"). '
        + 'Add a PNG, re-run the script.',
    bodies: names,
};

mkdirSync(OUT_DIR, {recursive: true});
writeFileSync(OUT, JSON.stringify(manifest, null, 2) + '\n');
console.log(`wrote ${OUT} (${names.length} bodies: ${names.join(', ')})`);
