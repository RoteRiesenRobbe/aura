#!/usr/bin/env node
/**
 * Packs the PONETI icons Aura uses into texture atlases and publishes them into
 * the frontend build output. A BUILD STEP: package.json runs it after
 * `npm run build` (postbuild, because webpack.prod.js wipes dist/ first) and
 * before `npm run start`.
 *
 *   node tools/pack-icons.mjs                 # the build step
 *   node tools/pack-icons.mjs --self-test     # exercises every path on a fake pack, no licence needed
 *
 * Input:  frontend/src/client-data/icons/pack-manifest.json  (committed: name -> path in the pack)
 *         $AURA_ICON_PACK_DIR/<path>                          (the raw pack, NEVER in the repo)
 * Built:  frontend/icons-prebuilt/atlas-<hash>.png             (one or more 2048² sheets, LOCAL, gitignored)
 *         frontend/icons-prebuilt/icons.json                   (name -> {atlas, x, y, w, h}, plus atlasSize/iconSize)
 * Served: frontend/dist/icons/                                 (a copy of the prebuilt set, made on every run)
 *
 * Two steps, and only the first needs the pack:
 *   1. BUILD, AURA_ICON_PACK_DIR set (the seat holder): pack the manifest into
 *      frontend/icons-prebuilt/. Fails, naming the fix, when the folder is
 *      missing, when a manifest entry has no file (all listed at once), when a
 *      source is not 256×256, or when the manifest is malformed.
 *   2. PUBLISH, always: copy frontend/icons-prebuilt/ to frontend/dist/icons/,
 *      so `npm run build` wiping dist/ never needs the pack again. With no
 *      prebuilt set (every clone but the seat holder's, while the atlases stay
 *      out of git: THIRD_PARTY.md) it writes an empty lookup, prints one notice
 *      line and exits 0: the game then draws the glyphs and the committed
 *      portraits.
 *
 * Deterministic: entries sort by name, so the same manifest and pack give the
 * same bytes, and the atlas file name is the content hash of the sheet.
 */
import {copyFileSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, unlinkSync, writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import os from 'node:os';
import path from 'node:path';
import {
    ATLAS_FILE, ATLAS_SIZE, ENV_PACK_DIR, GUTTER, ICON_SIZE, LOOKUP_NAME, MANIFEST_PATH, OUT_DIR, PREBUILT_DIR, ROOT,
    layoutGrid, readManifest, rel, resolvePackDir, sha256,
} from './icon-pack-common.mjs';

// sharp lives under frontend/node_modules (a declared devDependency there).
const sharp = createRequire(path.join(ROOT, 'frontend/package.json'))('sharp');

function parseArgs(argv) {
    const opts = {manifest: MANIFEST_PATH, out: OUT_DIR, prebuilt: PREBUILT_DIR, pack: undefined, selfTest: false};
    for (let i = 0; i < argv.length; i++) {
        const a = argv[i];
        if (a === '--self-test') opts.selfTest = true;
        else if (a === '--manifest') opts.manifest = path.resolve(argv[++i]);
        else if (a === '--out') opts.out = path.resolve(argv[++i]);
        else if (a === '--prebuilt') opts.prebuilt = path.resolve(argv[++i]);
        else if (a === '--pack') opts.pack = path.resolve(argv[++i]);
        else throw new Error(`unknown argument ${a}`);
    }
    return opts;
}

function writeLookup(outDir, lookup) {
    mkdirSync(outDir, {recursive: true});
    writeFileSync(path.join(outDir, LOOKUP_NAME), JSON.stringify(lookup, null, 2) + '\n');
}

function removeStaleAtlases(outDir) {
    if (!existsSync(outDir)) return;
    for (const name of readdirSync(outDir)) {
        if (ATLAS_FILE.test(name)) unlinkSync(path.join(outDir, name));
    }
}

/**
 * Step 2: copy the prebuilt set (lookup + the atlases it names) into the served
 * directory, or an empty lookup when there is no prebuilt set to copy.
 */
function publish(prebuilt, out, log) {
    const lookupFile = path.join(prebuilt, LOOKUP_NAME);
    removeStaleAtlases(out);
    if (!existsSync(lookupFile)) {
        log(`🖼  icons: no prebuilt set at ${rel(prebuilt)}/ and ${ENV_PACK_DIR} is not set: this build has no pack icons. See README "Icons (PONETI pack)".`);
        writeLookup(out, {_comment: `GENERATED by tools/pack-icons.mjs without a prebuilt set or ${ENV_PACK_DIR}: no pack icons in this build.`, iconSize: ICON_SIZE, atlasSize: ATLAS_SIZE, atlases: [], icons: {}});
        return {atlases: [], icons: 0};
    }
    const lookup = JSON.parse(readFileSync(lookupFile, 'utf8'));
    mkdirSync(out, {recursive: true});
    for (const atlas of lookup.atlases) {
        copyFileSync(path.join(prebuilt, atlas), path.join(out, atlas));
    }
    copyFileSync(lookupFile, path.join(out, LOOKUP_NAME));
    return {atlases: lookup.atlases, icons: Object.keys(lookup.icons).length};
}

export async function pack({manifest = MANIFEST_PATH, out = OUT_DIR, prebuilt = PREBUILT_DIR, pack, env = process.env, log = console.log} = {}) {
    const entries = readManifest(manifest);

    if (!pack && !env[ENV_PACK_DIR]) {
        const published = publish(prebuilt, out, log);
        if (published.atlases.length > 0) {
            log(`🖼  icons: ${published.icons} prebuilt icon(s) in ${published.atlases.length} atlas(es) copied from ${rel(prebuilt)}/ to ${rel(out)}/ (${entries.length} in the manifest; repacking needs ${ENV_PACK_DIR}).`);
        }
        return {...published, skipped: true};
    }

    const packDir = resolvePackDir(pack, env);

    const missing = entries.filter(({file}) => !existsSync(path.join(packDir, file)));
    if (missing.length > 0) {
        throw new Error(
            `${missing.length} manifest icon(s) not found under ${ENV_PACK_DIR}=${packDir}:\n` +
            missing.map(({name, file}) => `  ${name} -> ${file}`).join('\n') +
            `\nFix the path in ${rel(manifest)} or check the pack export.`);
    }

    const sources = [];
    for (const {name, file} of entries) {
        const abs = path.join(packDir, file);
        const meta = await sharp(abs).metadata();
        if (meta.width !== ICON_SIZE || meta.height !== ICON_SIZE) {
            throw new Error(`${name} -> ${file} is ${meta.width}×${meta.height}, the pack format is ${ICON_SIZE}×${ICON_SIZE}`);
        }
        sources.push({name, file, buffer: await sharp(abs).ensureAlpha().png().toBuffer()});
    }

    const {cells, atlasCount} = layoutGrid(sources.length, {atlasSize: ATLAS_SIZE, iconSize: ICON_SIZE, gutter: GUTTER});
    const atlasNames = [];
    const sheets = [];
    for (let a = 0; a < atlasCount; a++) {
        const composites = [];
        cells.forEach((cell, i) => {
            if (cell.atlas === a) composites.push({input: sources[i].buffer, left: cell.x, top: cell.y});
        });
        const sheet = await sharp({
            create: {width: ATLAS_SIZE, height: ATLAS_SIZE, channels: 4, background: {r: 0, g: 0, b: 0, alpha: 0}},
        }).composite(composites).png({compressionLevel: 9}).toBuffer();
        sheets.push(sheet);
        atlasNames.push(`atlas-${sha256(sheet).slice(0, 12)}.png`);
    }

    removeStaleAtlases(prebuilt);
    mkdirSync(prebuilt, {recursive: true});
    sheets.forEach((sheet, a) => writeFileSync(path.join(prebuilt, atlasNames[a]), sheet));

    const icons = {};
    sources.forEach(({name}, i) => {
        const {atlas, x, y, w, h} = cells[i];
        icons[name] = {atlas: atlasNames[atlas], x, y, w, h};
    });
    writeLookup(prebuilt, {
        _comment: 'GENERATED by tools/pack-icons.mjs from pack-manifest.json - do not hand-edit, do not commit (THIRD_PARTY.md).',
        iconSize: ICON_SIZE,
        atlasSize: ATLAS_SIZE,
        atlases: atlasNames,
        icons,
    });
    publish(prebuilt, out, log);
    log(`🖼  icons: ${sources.length} packed into ${atlasCount} atlas(es) at ${rel(prebuilt)}/, copied to ${rel(out)}/`);
    return {atlases: atlasNames, icons: sources.length, skipped: false};
}

